// Get unique countries for filtering
export const getUniqueCountries = (alliances: Alliance[]): string[] => {
  const countries = alliances.map(alliance => alliance.country);
  return Array.from(new Set(countries)).sort();
};

// Filter functions
export const filterByCountry = (
  alliances: Alliance[],
  country: string
): Alliance[] => {
  if (country === 'All') return alliances;
  return alliances.filter(alliance => alliance.country === country);
};

export const paginateAlliances = (
  alliances: Alliance[],
  page: number,
  itemsPerPage: number = 24
): Alliance[] => {
  const startIndex = (page - 1) * itemsPerPage;
  return alliances.slice(startIndex, startIndex + itemsPerPage);
};

export const getTotalPages = (
  totalItems: number,
  itemsPerPage: number = 24
): number => {
  return Math.ceil(totalItems / itemsPerPage);
};
